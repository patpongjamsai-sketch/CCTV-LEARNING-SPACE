// Returns the full 10 questions for any unit from U01 to U08
export function getUnitExamQuestions(unitId: string): ExamQuestion[] {
    const normalized = unitId.toUpperCase();
    if (UNIT_EXAM_QUESTIONS[normalized]) {
        return UNIT_EXAM_QUESTIONS[normalized];
    }

    // Fallback if needed
    return UNIT_EXAM_QUESTIONS.U01 || [];
}

// Returns the single question for a specific lesson (e.g. 'U02-L03')
export function getQuestionByLessonId(lessonId: string): ExamQuestion | undefined {
    const target = lessonId.trim().toUpperCase();
    for (const questions of Object.values(UNIT_EXAM_QUESTIONS)) {
        const found = questions.find((q) => q.lessonId.toUpperCase() === target);
        if (found) return found;
    }
    return undefined;
}
